    rawBouquets: List<BouquetSummary>,
    allChannels: List<TvChannel>,
    vpnStatus: CloudflareTunnelStatus,
    compact: Boolean,
    onReconnectVpn: () -> Unit,
    onUpdatePreferences: (PlayerPreferences) -> Unit
